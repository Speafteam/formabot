def estimate_minutes(items: list[dict]) -> int:
    """Грубая оценка длительности: работа плюс отдых между подходами."""
    total = 0.0
    for e in items:
        if e["timed"]:
            # "10 мин" или "45 сек"
            num = "".join(c for c in e["reps"] if c.isdigit())
            value = int(num) if num else 1
            per_set = value if "мин" in e["reps"] else value / 60
            total += per_set * e["sets"]
            total += 0.5 * max(e["sets"] - 1, 0)
        else:
            total += e["sets"] * 0.75          # подход около 45 секунд
            total += (e["sets"] - 1) * 2       # отдых 2 минуты
            total += 1.5                       # переход к снаряду
    return round(total)


WEEKDAYS = ["Понедельник", "Вторник", "Среда", "Четверг", "Пятница",
            "Суббота", "Воскресенье"]


def week_plan(goal: str, place: str, kind: str, start_ordinal: int) -> list[dict]:
    """Что стоит в расписании на семь дней вперёд, начиная с сегодня.

    Программа зависит от дня, поэтому её достаточно пересобрать на каждый
    день — состав получится ровно тот, который придёт человеку утром.
    """
    days = []
    for offset in range(7):
        index = start_ordinal + offset
        morning = build(goal, place, kind, "am", index)
        evening = build(goal, place, "cardio", "pm", index)
        days.append(
            {
                "offset": offset,
                "weekday": WEEKDAYS[(start_ordinal + offset - 1) % 7],
                "am_title": morning["title"],
                "am_minutes": morning["minutes"],
                "pm_title": evening["title"],
                "pm_minutes": evening["minutes"],
            }
        )
    return days


def render_week(days: list[dict], place: str, kind: str) -> str:
    lines = [
        f"<b>План на неделю</b>\n{PLACES[place]} · {KINDS[kind]}", ""
    ]
    for day in days:
        mark = "Сегодня" if day["offset"] == 0 else day["weekday"]
        lines.append(
            f"<b>{mark}</b>\n"
            f"  утро — {day['am_title']}, {day['am_minutes']} мин\n"
            f"  вечер — {day['pm_title']}, {day['pm_minutes']} мин"
        )
    lines += ["", "<i>Семь дней расписаны. Осталось прийти.</i>"]
    return "\n".join(lines)


def render(program: dict) -> str:
    """Программа текстом для сообщения в чат."""
    lines = [f"<b>{program['title']}</b> · {PLACES[program['place']]} · "
             f"около {program['minutes']} мин", ""]
    block = None
    for e in program["items"]:
        if e["block"] != block:
            block = e["block"]
            lines.append(f"<i>{block}</i>")
        count = f"{e['sets']} × {e['reps']}" if e["sets"] > 1 else e["reps"]
        lines.append(f"  • {e['name']} — {count}")
    return "\n".join(lines)

def _tune_for_goal(items: list[dict], goal: str) -> list[dict]:
    """Правка объёма под цель."""
    out = []
    for item in items:
        e = dict(item)
        if e["block"] != "Основной блок":
            out.append(e)
            continue
        if goal == "gain":
            # Масса — меньше повторов, больше подходов.
            e["note"] += " Работаем в тяжёлом весе, последние повторы трудные."
        elif goal == "lose":
            e["note"] += " Отдых короткий, темп держим."
        elif goal == "stretch":
            e["sets"] = max(2, e["sets"] - 1)
            e["note"] += " Амплитуда важнее веса."
        out.append(e)
    return out


def build(goal: str, place: str, kind: str, slot: str, day_index: int = 0) -> dict:
    """Собирает программу.

    slot: "am" — утренняя полная, "pm" — вечерний короткий блок.
    day_index используется, чтобы программы чередовались изо дня в день.
    """
    if slot == "pm":
        return _evening(goal, place, day_index)

    if kind == "cardio":
        main = list(CARDIO[place])
        title = f"Кардио, {PLACES[place].lower()}"
    else:
        variants = STRENGTH[place]
        which = day_index % len(variants)
        main = list(variants[which])
        # В зале программа чередуется: чётный день низ, нечётный верх.
        labels = ["низ тела", "верх тела"] if place == "gym" else ["всё тело"]
        title = f"Силовая, {labels[which % len(labels)]}"

    main = _tune_for_goal(main, goal)
    items = warmup(place) + main + cooldown(15)
    return {
        "title": title,
        "place": place,
        "kind": kind,
        "slot": "am",
        "items": items,
        "minutes": estimate_minutes(items),
    }



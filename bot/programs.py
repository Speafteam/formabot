def video(query: str) -> str:
    return "https://www.youtube.com/results?search_query=" + quote_plus(
        query + " техника выполнения"
    )


def ex(name, sets, reps, note, *, timed=False, block="Основной блок"):
    return {
        "name": name,
        "sets": sets,
        "reps": reps,
        "note": note,
        "video": video(name),
        "timed": timed,
        "block": block,
    }


